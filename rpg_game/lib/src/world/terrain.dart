  /// 名前から地形を決める。見つからなければ [fallback]
  static Terrain fromName(String name, {Terrain fallback = meadow}) {
    for (final (word, t) in _keywords) {
      if (name.contains(word)) return t;
    }
    return fallback;
  }

  /// ステージの地形。名前から、見つからなければ地方（草原・海岸など）から決める。
  /// ボスのエリアは地形はそのままで、マップ側で「ボスの間」の飾りがつく。
  static Terrain of(StageDef stage) =>
      fromName(stage.name, fallback: fromName(stage.region));
