enum Layout {
  /// ひらけた土地に、木や岩がぽつぽつある
  open,

  /// 木や岩がかたまって、くねくねした道になる（森・洞窟）
  dense,

  /// 川・海・雲の切れ目を、橋でわたる
  water,

  /// 柱・本棚・家などが規則正しく並ぶ（建物の中や町）
  grid,
}

