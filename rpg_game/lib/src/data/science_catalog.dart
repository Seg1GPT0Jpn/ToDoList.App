  static StageDef _stage(ScienceBranch b, int order, int k, _Area a) {
    final boss = k == 8 || k == 16;
    final calcHeavy = b.id == 'physics' || b.id == 'chemistry';
    final even =
        calcHeavy ? QuestionCategory.calculation : QuestionCategory.thinking;
    final setIds = [
      for (var n = boss ? (k == 8 ? 1 : 9) : k; n <= k; n++) setId(b.id, n),
    ];
    return StageDef(
      id: 'science_${b.id}_${_two(k)}',
      worldId: worldId,
      order: order,
      branch: b.id,
      branchOrder: k,
      name: a.place,
      region: k <= 8 ? b.basic : b.advanced,
      questionSetIds: setIds,
      grammarTheme: a.theme,
      vocabLevel: k <= 8 ? b.basic : b.advanced,
      expReward: _exp[k - 1],
      timeLimitSeconds: calcHeavy ? 30 : 25,
      readingTimeLimitSeconds: 60,
      recommendedLevel: _lv[k - 1],
      isBoss: boss,
      rewardCardId: _rewards[k],
      enemy: EnemyDef(
        id: 'sci_${b.id}_${_two(k)}',
        name: a.enemy,
        look: a.look,
        color: a.color,
        maxHp: _hp[k - 1],
        attack: _atk[k - 1],
        description: a.description,
        weakness: boss ? even : (k.isOdd ? QuestionCategory.knowledge : even),
        armorCategory: boss ? QuestionCategory.knowledge : null,
        armor: k == 8 ? 2 : (k == 16 ? 3 : 0),
        introLine: a.intro,
        defeatLine: a.defeat,
      ),
    );
  }

