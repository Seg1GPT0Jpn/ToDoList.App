def int_wrongs(ans):
    deg=int(ans[-2]) if ans[-3].isdigit()==False else int(ans[-3:-1])
    deg=int(''.join(ch for ch in ans if ch.isdigit()))
    qs=QUAL_P if deg in(1,4,5,8) else QUAL_M
    w=[q+str(deg)+'度' for q in qs]
    w+=[('長' if d not in(1,4,5,8) else '完全')+str(d)+'度' for d in (deg-1,deg+1) if 1<=d<=8]
    return w
