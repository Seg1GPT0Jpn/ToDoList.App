"""和の礎の国（国語）：小1〜中3。"""
import random

from lib import Q


_cursor = {}


def _take(pairs, n, kind):
    """語のリストを決まった順にまぜ、まだ使っていない語から n 個とる（読み・書きで別々）。"""
    key = (pairs[0][0], kind)
    if key not in _cursor:
        order = pairs[:]
        random.Random(pairs[0][0] + kind).shuffle(order)
        _cursor[key] = [order, 0]
    order, i = _cursor[key]
    assert i + n <= len(order), ('語が足りない', key, i + n, len(order))
    _cursor[key][1] = i + n
    return order[i:i + n]


def yomi(pairs, n, seed, word='かん字'):
    """[(漢字の語, 読み)] から読みの4択を n 問。"""
    r = random.Random(seed)
    out = []
    for k, y in _take(pairs, n, 'yomi'):
        others = [p[1] for p in pairs if p[1] != y]
        r.shuffle(others)
        # 読みが近い長さのものを先に
        others.sort(key=lambda x: abs(len(x) - len(y)))
        out.append(Q('k', f'「{k}」の読みは？', y, others[:3], f'{k}（{y}）'))
    return out


def kaki(pairs, n, seed, word='漢字'):
    """[(漢字の語, 読み)] から書きの4択を n 問。"""
    r = random.Random(seed)
    out = []
    for k, y in _take(pairs, n, 'kaki'):
        others = [p[0] for p in pairs if p[0] != k]
        r.shuffle(others)
        others.sort(key=lambda x: abs(len(x) - len(k)))
        verb = 'かくと' if word == 'かん字' else '書くと'
        out.append(Q('k', f'「{y}」を{word}で{verb}？', k, others[:3], f'{y} ＝ {k}'))
    return out


def R_(text, p, a, w, e):
    """文章を読んで答える問題（s に文章）。"""
    return Q('t', p, a, w, e, s=text)


