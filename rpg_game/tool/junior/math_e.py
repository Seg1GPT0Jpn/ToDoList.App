            a, b, c = r.randint(10, 30), r.randint(2, 9), r.randint(2, 5)
            return calc(f'({a} − {b}) × {c} は？', (a - b) * c, '( ) の中を先に計算する。', w=[a - b + c, (a - b) * c + c, (a + b) * c])
