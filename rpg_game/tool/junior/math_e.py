    def fmul(r):
        a, b = Fr(r.randint(1, 8), r.randint(2, 9)), Fr(r.randint(1, 8), r.randint(2, 9))
        if a.denominator == 1 or b.denominator == 1:
            return None
        p = a * b
        return Q('c', f'{frac(a)} × {frac(b)} は？', frac(p), [frac(a + b), f'{a.numerator * b.numerator}/{a.denominator + b.denominator}', frac(a / b) if a / b != p else frac(p * 2)], '分母どうし、分子どうしをかける（とちゅうで約分すると楽）。')

