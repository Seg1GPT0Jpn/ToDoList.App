    from math import gcd

    def ratio(r):
        a, b = r.randint(2, 9), r.randint(2, 9)
        if gcd(a, b) != 1:
            return None
        k = r.randint(2, 8)
        kind = r.randint(0, 1)
        if kind == 0:
            return Q('c', f'{a * k}:{b * k} をかんたんな比にすると？', f'{a}:{b}', [f'{b}:{a}', f'{a * k}:{b}', f'{a + 1}:{b + 1}'], f'両方を{k}でわる。')
        return calc(f'{a}:{b} = {a * k}:x のとき、xは？', b * k, f'{a}を{k}倍して{a * k}。{b}も{k}倍。', w=[b * k + k, a * k, b + k])

