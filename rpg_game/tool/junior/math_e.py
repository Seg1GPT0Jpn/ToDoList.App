    def mixed(r):
        k = r.randint(0, 2)
        if k == 0:
            a, b, c = r.randint(2, 9), r.randint(2, 9), r.randint(2, 9)
            return calc(f'{a} + {b} × {c} は？', a + b * c, 'かけ算をたし算より先に計算する。', w=[(a + b) * c, a + b + c, a * b + c])
