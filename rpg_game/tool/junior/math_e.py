    def fdiv(r):
        a, b = Fr(r.randint(1, 8), r.randint(2, 9)), Fr(r.randint(1, 8), r.randint(2, 9))
        if a.denominator == 1 or b.denominator == 1 or a == b:
            return None
        q = a / b
        return Q('c', f'{frac(a)} ÷ {frac(b)} は？', frac(q), [frac(a * b), frac(b / a) if b / a != q else frac(q + 1), f'{a.numerator}/{b.denominator}' if Fr(a.numerator, b.denominator) != q else frac(q * 2)], 'わる数の逆数をかける。')

