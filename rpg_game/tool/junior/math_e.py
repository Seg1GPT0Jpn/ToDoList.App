def boss(R, *gens, seed=0, n=12):
    """ボスのエリア：前のエリアの問題の作り方を使って、新しいまとめの問題を作る
    （同じルートでもう出した問いはのぞく）。"""
    gens = list(gens)
    used = {q['p'] for a in R.areas for q in a.qs}
    return uniq(lambda r: r.choice(gens)(r), n, seed, exclude=used)


