def _spread_answers():
    """問5〜問8の単純な4択は、正答の位置が1→2→3→4…と順にずれるように並べかえる（ほかの選択肢の順は保つ）。"""
    k = 0
    for s in SECTIONS[4:]:
        for q in s["questions"]:
            if q["kind"] != "mark" or len(q["choices"]) != 4:
                continue
            right = q["choices"][q["ans"] - 1]
            others = [c for c in q["choices"] if c != right]
            pos = (k * 3 + k // 4) % 4
            q["choices"] = others[:pos] + [right] + others[pos:]
            q["ans"] = pos + 1
            k += 1


_spread_answers()
