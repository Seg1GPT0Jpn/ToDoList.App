def municipal_map():
    """33市町村に番号をつけた地図と一覧"""
    m = F._MAP
    order = list(F.NAMES)
    out = [f'<svg viewBox="-10 -10 {m["W"] + 20} {m["H"] + 20}" width="100%" xmlns="http://www.w3.org/2000/svg" '
           f'font-family="sans-serif"><rect x="-10" y="-10" width="{m["W"] + 20}" height="{m["H"] + 20}" fill="#e6eff6"/>']
    for code, v in m["m"].items():
        out.append(f'<path d="{v["d"]}" fill="#fbfaf6" stroke="#1b2b44" stroke-width="0.9"/>')
    for i, code in enumerate(order, 1):
        x, y = m["m"][code]["c"]
        out.append(f'<text x="{x}" y="{y + 5}" text-anchor="middle" font-size="15" font-weight="bold" fill="#c0392b" '
                   f'stroke="#fff" stroke-width="4" paint-order="stroke">{i}</text>')
    out.append('<text x="330" y="470" font-size="22" fill="#5b7895" letter-spacing="8">相 模 湾</text></svg>')
    legend = "".join(f"<span><b>{i}</b> {e(F.NAMES[c])}</span>" for i, c in enumerate(order, 1))
    return "".join(out), legend


def table(head, rows, widths=None):
    h = "".join(f'<th{f" style=width:{w}" if w else ""}>{c}</th>' for c, w in zip(head, widths or [None] * len(head)))
    return '<table class="t"><tr>' + h + "</tr>" + "".join(
        "<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows) + "</table>"


def ul(items):
    return "<ul>" + "".join(f"<li>{x}</li>" for x in items) + "</ul>"


def chapter(no, title, body):
    return f'<section><h2><span>{no}</span>{title}</h2>{body}</section>'


