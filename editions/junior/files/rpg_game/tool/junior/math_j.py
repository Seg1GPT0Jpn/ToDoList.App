def sgn(x):
    return f'({x})' if x < 0 else str(x)


def lin(a, b, v='x'):
    """ax + b を見やすく"""
    s = '' if a == 1 else '−' if a == -1 else str(a).replace('-', '−')
    s += v
    if b > 0:
        s += f' + {b}'
    elif b < 0:
        s += f' − {-b}'
    return s


def mn(x):
    return str(x).replace('-', '−')


