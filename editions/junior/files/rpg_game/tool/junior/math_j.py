        ans = f'{lin(a + c, 0, "x")} {"+" if b + d > 0 else "−"} {abs(b + d) if abs(b + d) != 1 else ""}y'
        w1 = f'{lin(a - c, 0, "x") if a != c else "0x"} {"+" if b - d > 0 else "−"} {abs(b - d) if abs(b - d) != 1 else ""}y'
        w2 = f'{lin(a + c, 0, "x")} {"+" if b - d > 0 else "−"} {abs(b - d) if abs(b - d) != 1 else ""}y'
