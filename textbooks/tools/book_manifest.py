def iter_units(subject):
    """(part の見出しの並び, unit) を順に返す。"""
    def walk(parts, trail):
        for p in parts:
            t = trail + [p["title"]]
            if "parts" in p:
                yield from walk(p["parts"], t)
            for u in p.get("units", []):
                yield t, u
    yield from walk(subject["parts"], [])


